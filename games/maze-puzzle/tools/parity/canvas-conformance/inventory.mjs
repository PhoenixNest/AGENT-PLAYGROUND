// Static scan of the CanvasRenderingContext2D surface used by web/engine/renderer.js and the canvas
// setup in web/main.js. Writes INVENTORY.md next to this file. Never modifies web/.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webDir = path.resolve(here, "../../../games/maze-puzzle/web");
const files = [
  { name: "engine/renderer.js", text: fs.readFileSync(path.join(webDir, "engine/renderer.js"), "utf8") },
  { name: "main.js", text: fs.readFileSync(path.join(webDir, "main.js"), "utf8") },
];

const rendererLines = files[0].text.split("\n");
const polyfillRange = [10, 35];

const methodNames = [
  "beginPath", "closePath", "moveTo", "lineTo", "arc", "arcTo", "ellipse", "quadraticCurveTo",
  "bezierCurveTo", "rect", "roundRect", "fill", "stroke", "clip", "fillRect", "strokeRect",
  "clearRect", "save", "restore", "translate", "rotate", "scale", "setTransform", "transform",
  "resetTransform", "setLineDash", "createLinearGradient", "createRadialGradient",
  "createConicGradient", "createPattern", "drawImage", "fillText", "strokeText", "measureText",
  "getImageData", "putImageData", "isPointInPath",
];
const propNames = [
  "fillStyle", "strokeStyle", "lineWidth", "lineCap", "lineJoin", "miterLimit", "lineDashOffset",
  "shadowBlur", "shadowColor", "shadowOffsetX", "shadowOffsetY", "globalAlpha",
  "globalCompositeOperation", "font", "textAlign", "textBaseline", "direction", "fontKerning",
  "imageSmoothingEnabled", "imageSmoothingQuality", "filter",
];

const hits = { methods: {}, props: {}, gradient: [], values: {}, colors: { fillStyle: [], strokeStyle: [], shadowColor: [], addColorStop: [] } };
const push = (bucket, key, loc) => { (bucket[key] ??= []).push(loc); };

rendererLines.forEach((line, i) => {
  const n = i + 1;
  const code = line.replace(/\/\/.*$/, "");
  const inPolyfill = n >= polyfillRange[0] && n <= polyfillRange[1];
  for (const m of methodNames) {
    const re = new RegExp(`\\b(?:ctx|this)\\.${m}\\(`, "g");
    const count = (code.match(re) || []).length;
    for (let k = 0; k < count; k++) push(hits.methods, m, inPolyfill ? `${n}(polyfill)` : `${n}`);
  }
  for (const p of propNames) {
    const re = new RegExp(`\\bctx\\.${p}\\s*=(?!=)\\s*(.*?);?\\s*$`);
    const mm = code.match(re);
    if (mm) {
      push(hits.props, p, `${n}`);
      if (["lineCap", "lineJoin", "textAlign", "textBaseline", "font", "globalCompositeOperation", "imageSmoothingEnabled"].includes(p)) {
        push(hits.values, `${p} = ${mm[1].trim()}`, `${n}`);
      }
      if (["fillStyle", "strokeStyle", "shadowColor"].includes(p)) hits.colors[p].push({ n, expr: mm[1].trim() });
    }
  }
  const stop = code.match(/\.addColorStop\(\s*[^,]+,\s*(.*)\);\s*$/);
  if (stop) hits.colors.addColorStop.push({ n, expr: stop[1].trim() });
});

function classify(expr) {
  if (/^"#[0-9a-fA-F]{6}"$/.test(expr)) return "hex6 literal";
  if (/^"#[0-9a-fA-F]{3}"$/.test(expr)) return "hex3 literal";
  if (/^"#[0-9a-fA-F]{8}"$/.test(expr)) return "hex8 literal";
  if (/^"rgba\(/.test(expr)) return "rgba() literal";
  if (/^"rgb\(/.test(expr)) return "rgb() literal";
  if (/^"hsla?\(/.test(expr)) return "hsl() literal";
  if (/^`rgba\(/.test(expr)) return "rgba() template with computed alpha";
  if (/\+\s*"[0-9a-fA-F]{2}"/.test(expr)) return "variable + 2-digit alpha suffix (hex8 after concatenation)";
  if (/\|\|/.test(expr)) return "variable with literal fallback";
  if (/^[A-Za-z_][\w.\[\]]*$/.test(expr)) return "variable / property (value is a hex6 or gradient)";
  return "other: " + expr;
}

const colorSummary = {};
for (const [prop, list] of Object.entries(hits.colors)) {
  for (const { n, expr } of list) {
    const c = classify(expr);
    colorSummary[`${prop}: ${c}`] ??= [];
    colorSummary[`${prop}: ${c}`].push(n);
  }
}

const compress = (arr) => {
  const nums = arr.filter((s) => typeof s === "number" || /^\d+$/.test(String(s)));
  return arr.join(", ");
};

const out = [];
out.push("# Canvas 2D API inventory (web/engine/renderer.js, web/main.js)");
out.push("");
out.push("Generated by `inventory.mjs` (static scan, `node inventory.mjs`). Line numbers refer to `web/engine/renderer.js` unless a file is named.");
out.push("The runtime histogram in the last section is produced by `record.mjs` from the recorded streams (what the app actually executes).");
out.push("");
out.push("## Canvas setup (`main.js`, `renderer.js`)");
out.push("");
out.push("| What | Where |");
out.push("| --- | --- |");
out.push("| `canvas.getContext(\"2d\")` default attributes (no `alpha:false`, no `desynchronized`, no `willReadFrequently`) | renderer.js:40 |");
out.push("| `dpr = Math.min(devicePixelRatio || 1, 3)`; backing store `round(w*dpr) x round(h*dpr)`; CSS size `w x h` px | renderer.js:79-86 |");
out.push("| `resize(w, h)` called from `initLayout()` with `frame.clientWidth/clientHeight` (or window size) | main.js:330-332 |");
out.push("| per frame: `setTransform(dpr,0,0,dpr,0,0)` then `clearRect(0,0,w,h)` | renderer.js:320-321 |");
out.push("| Result at the pass-bar geometry: 430 x 932 CSS px -> 1290 x 2796 backing store | SPEC section 2 |");
out.push("| No `getImageData`, `drawImage`, `createPattern`, `clip`, `globalCompositeOperation`, `lineJoin`, `miterLimit`, `imageSmoothing*`, `filter`, `measureText`, `fill(path|rule)`, `Path2D` anywhere | scan below |");
out.push("");
out.push("## Methods");
out.push("");
out.push("| Method | Count | Lines |");
out.push("| --- | ---: | --- |");
for (const m of methodNames) {
  const list = hits.methods[m];
  if (!list) continue;
  out.push(`| \`${m}\` | ${list.length} | ${compress(list)} |`);
}
out.push("");
out.push("Not used: " + methodNames.filter((m) => !hits.methods[m]).map((m) => `\`${m}\``).join(", ") + ".");
out.push("");
out.push("`roundRect` is used with a polyfill guard (lines 10-35, quadratic corners). Chromium 153 has a native `roundRect`, so the polyfill is **not** installed in the reference: the native implementation (elliptical-arc corners, `arcTo`-like conics) is what must be matched. Radii used are a single number (lines 1288, 1546, 1554, 1611, 1633, 1641, 1706, 1714, 1787, 1820).");
out.push("");
out.push("## Properties");
out.push("");
out.push("| Property | Assignments | Lines |");
out.push("| --- | ---: | --- |");
for (const p of propNames) {
  const list = hits.props[p];
  if (!list) continue;
  out.push(`| \`${p}\` | ${list.length} | ${compress(list)} |`);
}
out.push("");
out.push("Not used (state stays at the Chromium default): " + propNames.filter((p) => !hits.props[p]).map((p) => `\`${p}\``).join(", ") + ".");
out.push("");
out.push("Defaults that therefore matter: `lineJoin = \"miter\"`, `miterLimit = 10`, `lineCap = \"butt\"` until set, `shadowOffsetX/Y = 0`, `globalCompositeOperation = \"source-over\"`, `imageSmoothingEnabled = true`.");
out.push("");
out.push("## Enumerated values");
out.push("");
out.push("| Assignment | Count | Lines |");
out.push("| --- | ---: | --- |");
for (const [k, v] of Object.entries(hits.values).sort()) out.push(`| \`${k}\` | ${v.length} | ${v.join(", ")} |`);
out.push("");
out.push("## Colour syntaxes (static)");
out.push("");
out.push("| Property: syntax | Count | Lines |");
out.push("| --- | ---: | --- |");
for (const [k, v] of Object.entries(colorSummary).sort()) out.push(`| ${k} | ${v.length} | ${v.join(", ")} |`);
out.push("");
out.push("No `hsl()/hsla()`, named colours or `rgb()` are used. Computed colours: `(skin.haloColor || \"#818cf8\") + \"55\"` style hex8 strings (alpha 0x22..0xdd), `rgba(255, 255, 255, ${bAlpha})` with alpha in 0..1 with many decimals, and skin colours from `economy.js` `COSMETIC_CATALOG` (all `#rrggbb`).");
out.push("");
out.push("## Gradients");
out.push("");
out.push("| Kind | Lines |");
out.push("| --- | --- |");
const gl = [];
rendererLines.forEach((line, i) => {
  if (/createLinearGradient\(/.test(line)) gl.push(["linear", i + 1]);
  if (/createRadialGradient\(/.test(line)) gl.push(["radial", i + 1]);
});
for (const kind of ["linear", "radial"]) out.push(`| ${kind} | ${gl.filter((g) => g[0] === kind).map((g) => g[1]).join(", ")} |`);
out.push("");
out.push("Stops: 3-stop linear sky (hex6 stops, lines 415-418), funnel linear gradient with hex8 + `rgba(56,189,248,0.04)` stops (504-507), radial halo with hex8 stops ending in `rgba(0,0,0,0)` (591-594; transparent-black end stop makes premultiplied vs straight interpolation visible), bumper dome radial (928-). Radial gradients all have `r0 < r1`; the dome one has an off-centre inner circle (`x0 != x1`).");
out.push("");
out.push("## Transforms");
out.push("");
out.push("- `setTransform(dpr,0,0,dpr,0,0)` per frame (320).");
out.push("- `translate` + `rotate` + uniform `scale` nesting (`save`/`restore` depth <= 4).");
out.push("- One shear: `transform(1, 0, -0.22, 1, 0, 0)` (1698), booster gate; subsequent fills and strokes (round rects, text) are drawn under the shear.");
out.push("- Non-uniform scale is never used.");
out.push("");
out.push("## Text (see SPEC Appendix B for the per-site table)");
out.push("");
out.push("Fonts: `bold 13px Fredoka`, `11px Nunito`, `bold 10px Fredoka`, `900 10.5px Fredoka`, `bold 9.5px Fredoka`, `900 16px Fredoka` (all with `, sans-serif`). `textAlign = center` everywhere; `textBaseline = middle` in 5 sites, default `alphabetic` for floating text. One `strokeText` (floating text outline, `lineWidth` set by the caller, round joins are not requested so miter applies).");
out.push("");
const idxPath = path.join(here, "streams", "index.json");
if (fs.existsSync(idxPath)) {
  const idx = JSON.parse(fs.readFileSync(idxPath, "utf8"));
  const h = idx.histogram;
  const table = (title, obj) => {
    out.push(`### ${title}`);
    out.push("");
    out.push("| Name | Calls over " + idx.streams.length + " recorded frames |");
    out.push("| --- | ---: |");
    for (const [k, v] of Object.entries(obj).sort((a, b) => b[1] - a[1])) out.push(`| \`${k}\` | ${v} |`);
    out.push("");
  };
  out.push("## Runtime histogram (recorded streams: sectors 1/11/21/31/41 x f001, f060, f180, vfx1, vfx2, pause)");
  out.push("");
  table("Methods", h.methods);
  table("Property assignments", h.props);
  table("Colour syntaxes (runtime, after string building)", h.colors);
  table("Enumerated values", h.values);
}

fs.writeFileSync(path.join(here, "INVENTORY.md"), out.join("\n") + "\n");
